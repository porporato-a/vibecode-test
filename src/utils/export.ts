import { AnalyzedVideo } from '../types/video';

export function formatVideoAsMarkdown(video: AnalyzedVideo): string {
  const isWebPage = video.contentType === 'webpage';
  const dateStr = new Date(video.analyzedAt).toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  let md = `# ${video.title}\n\n`;
  if (isWebPage) {
    md += `**Type:** Web Page with Embedded Videos\n`;
    md += `**Source Webpage:** ${video.originalUrl}\n`;
    md += `**Domain/Publisher:** ${video.channelTitle}\n`;
    if (video.embeddedVideos && video.embeddedVideos.length > 0) {
      md += `**Embedded Videos (${video.embeddedVideos.length}):**\n`;
      video.embeddedVideos.forEach((ev, i) => {
        md += `  ${i + 1}. [${ev.title}](${ev.url})\n`;
      });
    }
  } else {
    md += `**Creator:** ${video.channelTitle}\n`;
    md += `**Video URL:** ${video.originalUrl}\n`;
  }
  md += `**Analyzed Date:** ${dateStr}\n`;
  if (video.summary.topics && video.summary.topics.length > 0) {
    md += `**Topics:** ${video.summary.topics.join(' · ')}\n`;
  }
  md += `\n---\n\n`;

  md += `## Executive Summary\n\n`;
  md += `${video.summary.executiveSummary}\n\n`;

  if (video.summary.coreHighlights && video.summary.coreHighlights.length > 0) {
    md += `## Core Highlights\n\n`;
    video.summary.coreHighlights.forEach((point) => {
      md += `- ${point}\n`;
    });
    md += `\n`;
  }

  if (video.summary.mainTakeaways && video.summary.mainTakeaways.length > 0) {
    md += `## Key Takeaways & Action Points\n\n`;
    video.summary.mainTakeaways.forEach((point) => {
      md += `1. ${point}\n`;
    });
    md += `\n`;
  }

  if (video.summary.keyQuotes && video.summary.keyQuotes.length > 0) {
    md += `## Memorable Quotes\n\n`;
    video.summary.keyQuotes.forEach((quote) => {
      md += `> "${quote}"\n\n`;
    });
  }

  if (video.userNotes) {
    md += `## Viewer Context & Notes\n\n`;
    md += `${video.userNotes}\n\n`;
  }

  md += `---\n*Generated by YouTube Video Intelligence Workspace*\n\n<!-- YOUTUBE_DATA: ${JSON.stringify(video)} -->\n`;
  return md;
}

export function formatArchiveAsMarkdown(videos: AnalyzedVideo[]): string {
  let md = `# YouTube Video Intelligence Archive\n\n`;
  md += `*Compendium of ${videos.length} analyzed reports & videos — Exported on ${new Date().toLocaleDateString()}*\n\n`;
  md += `---\n\n`;

  videos.forEach((video, index) => {
    const isWebPage = video.contentType === 'webpage';
    md += `### ${index + 1}. [${video.title}](${video.originalUrl})\n`;
    if (isWebPage) {
      md += `**Type:** Web Page Report (${video.embeddedVideos?.length || 1} embedded videos) · **Publisher:** ${video.channelTitle} · **Analyzed:** ${new Date(video.analyzedAt).toLocaleDateString()}\n\n`;
    } else {
      md += `**Channel:** ${video.channelTitle} · **Analyzed:** ${new Date(video.analyzedAt).toLocaleDateString()}\n\n`;
    }
    md += `**Executive Summary:** ${video.summary.executiveSummary}\n\n`;
    if (video.summary.coreHighlights && video.summary.coreHighlights.length > 0) {
      md += `**Core Highlights:**\n`;
      video.summary.coreHighlights.slice(0, 3).forEach((h) => {
        md += `- ${h}\n`;
      });
      md += `\n`;
    }
    md += `---\n\n`;
  });

  md += `<!-- ARCHIVE_DATA: ${JSON.stringify(videos)} -->\n`;
  return md;
}

export function downloadTextFile(filename: string, content: string, mimeType: string = 'text/plain') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function exportVideoMarkdown(video: AnalyzedVideo) {
  const safeTitle = (video.title || 'report_summary')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .slice(0, 40);
  const filename = `${safeTitle}_summary.md`;
  const content = formatVideoAsMarkdown(video);
  downloadTextFile(filename, content, 'text/markdown');
}

export function exportVideoJSON(video: AnalyzedVideo) {
  const safeTitle = (video.title || 'report_summary')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .slice(0, 40);
  const filename = `${safeTitle}_data.json`;
  const content = JSON.stringify(video, null, 2);
  downloadTextFile(filename, content, 'application/json');
}

export function exportArchiveMarkdown(videos: AnalyzedVideo[]) {
  const filename = `youtube_archive_${new Date().toISOString().slice(0, 10)}.md`;
  const content = formatArchiveAsMarkdown(videos);
  downloadTextFile(filename, content, 'text/markdown');
}

export function exportArchiveJSON(videos: AnalyzedVideo[]) {
  const filename = `youtube_archive_${new Date().toISOString().slice(0, 10)}.json`;
  const content = JSON.stringify(videos, null, 2);
  downloadTextFile(filename, content, 'application/json');
}
